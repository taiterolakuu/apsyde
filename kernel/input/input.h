#ifndef INPUT_H
#define INPUT_H
#include <stdint.h>

/* ============ Источники ввода ============ */

#define INPUT_SRC_DEMO   0   /* скриптованные команды (для MacBook без USB HID) */
#define INPUT_SRC_PS2    1   /* PS/2 клавиатура (QEMU, старое железо) */
#define INPUT_SRC_USB    2   /* USB HID клавиатура (MacBook, современное железо) */

/* ============ Инициализация ============ */

/* Вызывается после keyboard_init (PS/2) и после usb_kbd_init (когда будет).
 * Определяет доступные источники и настраивает приоритет. */
void input_init(void);

/* ============ Получение символов ============ */

/* Возвращает следующий символ из активного источника или -1 если пусто.
 * Автоматически переключается между источниками по приоритету:
 *   USB > PS/2 > DEMO
 * Если в PS/2/USB есть ввод — он используется.
 * Если оба молчат INPUT_DEMO_TIMEOUT_MS — активируется DEMO. */
int input_getchar(void);

/* Блокирующий вариант: ждёт символ (в том числе от DEMO). */
int input_getchar_blocking(void);

/* ============ Управление источником ============ */

/* Принудительно выбрать источник. -1 = auto. */
void input_set_source(int src);
int  input_get_source(void);

/* Сброс таймаута DEMO — вызывается, когда пользователь нажал клавишу
 * на PS/2 или USB. Даёт пользователю ещё N секунд на ввод перед
 * тем, как DEMO снова возьмёт управление. */
void input_reset_demo_timeout(void);

#endif